// Helper methods
const CatalogService = {
  getAll: function() {
    return INITIAL_CATALOG;
  },
  getById: function(id) {
    const numId = parseInt(id);
    return INITIAL_CATALOG.find(p => p.id === numId) || null;
  },
  getByCategory: function(cat) {
    if (!cat || cat.toLowerCase() === 'all') return INITIAL_CATALOG;
    return INITIAL_CATALOG.filter(p => p.category.toLowerCase() === cat.toLowerCase());
  },
  getCategories: function() {
    return Array.from(new Set(INITIAL_CATALOG.map(p => p.category)));
  },
  search: function(query) {
    if (!query) return INITIAL_CATALOG;
    const q = query.toLowerCase().trim();
    return INITIAL_CATALOG.filter(p => 
      p.name.toLowerCase().includes(q) ||
      (p.scientificName && p.scientificName.toLowerCase().includes(q)) ||
      p.category.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q) ||
      p.tags.some(t => t.toLowerCase().includes(q))
    );
  }
};

if (typeof window !== 'undefined') {
  window.INITIAL_CATALOG = INITIAL_CATALOG;
  window.CatalogService = CatalogService;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { INITIAL_CATALOG, CatalogService };
}
